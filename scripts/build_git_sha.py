# PlatformIO extra_scripts hook (pre).
#
# Generates include/git_sha.h (gitignored build artifact) so the M1 boot
# log can print BOOT ... git=<sha8> (FR-007). The header route is used
# instead of CPPDEF/CPPDEFINES because the espressif32 Arduino builder
# re-derives its own define lists and drops hook-level Appends. `include/`
# is on the include path by PlatformIO default, so no flag plumbing is
# needed. The hook runs on every `pio run -e esp32dev` invocation, so the
# header always matches the built commit. Falls back to "nogit" outside a
# git checkout.
import os
import subprocess


def _git_sha():
    try:
        out = subprocess.check_output(
            ["git", "rev-parse", "--short=8", "HEAD"],
            stderr=subprocess.DEVNULL,
            text=True,
        ).strip()
        return out if len(out) == 8 else "nogit"
    except Exception:
        return "nogit"


header = os.path.join("include", "git_sha.h")
content = "// Generated by scripts/build_git_sha.py - do not edit.\n"
content += '#define GIT_SHA "%s"\n' % _git_sha()
with open(header, "w") as f:
    f.write(content)
